// Writes supabase/seed.sql from the sample data in src/lib/sample.ts, so the SQL seed and the demo data
// cannot drift apart. Run with: npm run seed:gen
//
// tests/rls/seed.test.ts fails when the committed seed.sql is not what this script produces.

import { writeFileSync } from "node:fs";
import { register } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";
import type { ChangeEvent, FlagRecord } from "../src/lib/domain";

const ROWS_PER_INSERT = 100;

/** A SQL string literal. */
function text(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function textArray(values: readonly string[]): string {
  return `array[${values.map(text).join(", ")}]::text[]`;
}

function chunks<T>(items: readonly T[], size: number): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < items.length; i += size) out.push(items.slice(i, i + size));
  return out;
}

/** The whole seed file. Pure: the same records and events always give the same text. */
export function buildSeedSql(records: readonly FlagRecord[], events: readonly ChangeEvent[]): string {
  const lines: string[] = [
    "-- Generated by scripts/gen-seed.ts from src/lib/sample.ts. Do not edit by hand: run `npm run seed:gen`.",
    "--",
    "-- Made-up sample data: the three sample changes and the sample flagged filings. No names, no case",
    "-- numbers. It creates no accounts and no profiles. Sample rows have no author, no notes and no reasons.",
    "-- Run it as the project owner (supabase db reset does), not through the API.",
    "",
    "begin;",
    "",
    "insert into public.change_events (id, name, event_date, county, case_type, tag, description, created_by) values",
    events
      .map(
        (event) =>
          `  (${[text(event.id), text(event.name), `date ${text(event.date)}`, text(event.county), text(event.caseType), text(event.tag), text(event.description), "null"].join(", ")})`,
      )
      .join(",\n") + ";",
    "",
  ];

  for (const group of chunks(records, ROWS_PER_INSERT)) {
    lines.push(
      "insert into public.filing_flags (id, county, filed_on, case_type, form, tags, outcome, source, created_by, created_at) values",
      group
        .map((record) => {
          if (record.source !== "sample" || record.note !== null || record.reason !== null || record.createdBy !== null || record.batchId !== null) {
            throw new Error(`Record ${record.id} is not a plain sample row and cannot go in the seed.`);
          }
          return `  (${[
            text(record.id),
            text(record.county),
            `date ${text(record.date)}`,
            text(record.caseType),
            text(record.form),
            textArray(record.tags),
            text(record.outcome),
            "'sample'",
            "null",
            `timestamptz ${text(record.createdAt)}`,
          ].join(", ")})`;
        })
        .join(",\n") + ";",
      "",
    );
  }

  lines.push("commit;", "");
  return lines.join("\n");
}

// Node runs this file directly and strips the types, but it does not add the ".ts" that the imports
// inside src/lib leave off. This resolve hook adds it.
const RESOLVE_HOOK = `
export async function resolve(specifier, context, nextResolve) {
  if (/^\\.{1,2}\\//.test(specifier) && !/\\.[cm]?[jt]s$/.test(specifier)) return nextResolve(specifier + ".ts", context);
  return nextResolve(specifier, context);
}`;

async function main(): Promise<void> {
  register(`data:text/javascript,${encodeURIComponent(RESOLVE_HOOK)}`);
  const sample = await import("../src/lib/sample");
  const records = sample.makeSampleRecords();
  const target = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));
  writeFileSync(target, buildSeedSql(records, sample.SAMPLE_EVENTS));
  console.log(`Wrote ${target}: ${sample.SAMPLE_EVENTS.length} changes, ${records.length} flagged filings.`);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
